// 3D-модели техники обеих сторон (метры; x — вперёд, y — вправо, z — вверх; начало — центр на земле).
// Башни — отдельные модели с началом в оси погона (на земле), их высота задана абсолютно.
// Облик — по реальным классам машин: «Страж» ≈ Leopard 2A6, Т-84М ≈ Т-72Б3/Т-90 с «мангалом»,
// «Бастион» ≈ M2 Bradley, БМП-4 ≈ БМП-2, «Рысь» ≈ Stryker, БТР-90К ≈ БТР-82А, «Атлас» ≈ MAN HX,
// «Урал-К» ≈ Урал-4320, «Гром» ≈ PzH 2000, «Мста-К» ≈ 2С19, «Шквал» ≈ HIMARS, «Град-К» ≈ БМ-21,
// «Варан» ≈ M-ATV, «Тигр-К» ≈ ГАЗ «Тигр», «Щит» ≈ IRIS-T SLM, «Тор-К» ≈ «Тор-М2К».

import { Model, mat, hex, fbm, vnoise, mix } from './mesh3d.js';

const PAL = {
  blue: { c: ['#4d5b3a', '#5f4d36', '#27281f'], mark: hex('#3f7fe0'), light: hex('#a9c6ff') },
  red: { c: ['#58633f', '#2c2f23', '#83795a'], mark: hex('#d8433a'), light: hex('#ffb0a6') },
};
const DUST = hex('#7d6c50');
const set = (o, c) => { o[0] = c[0]; o[1] = c[1]; o[2] = c[2]; };

// Камуфляж + пыль у земли + потёртости; mark(o,x,y,z,n) — опознавательные знаки
function camo(side, seed = 0, mark = null, scale = 1) {
  const P = PAL[side];
  const c1 = hex(P.c[1]), c2 = hex(P.c[2]);
  return mat(P.c[0], {
    fn(o, x, y, z, n) {
      const v = fbm(x * 0.5 * scale + seed, y * 0.5 * scale + seed * 0.3, z * 0.5 * scale);
      if (v < 0.37) set(o, c1);
      else if (v > 0.67) set(o, c2);
      const dz = 1.0 - z;
      if (dz > 0) mix(o, DUST, Math.min(0.6, dz * 0.75) * (0.5 + 0.5 * vnoise(x * 2.5, y * 2.5, z * 4)));
      const sp = vnoise(x * 11 + 3, y * 11, z * 11);
      if (sp > 0.87) mix(o, [190, 182, 150], 0.12);
      if (mark) mark(o, x, y, z, n);
    },
  });
}
const flat = (c, o) => mat(c, o);
const STEEL = flat('#3b3d37');
const RUBBER = flat('#1c1c1a');
const GLASS = flat('#1b2831', { spec: 0.9, ao: false });
const LIGHT = flat('#d9d6be', { spec: 0.6, ao: false });
const BLACK = flat('#121311');
const WOOD = mat('#6a5236', { fn(o, x, y, z) { mix(o, [60, 44, 28], vnoise(x * 1.5, y * 40, z * 40) * 0.5); } });

// Гусеничные траки: чередование звеньев
const trackMat = mat('#2a2a25', {
  fn(o, x, y, z) {
    const t = (x * 6.5) % 1;
    if (t < 0 ? t + 1 < 0.35 : t < 0.35) mix(o, [70, 68, 58], 0.6);
    if (z < 0.5) mix(o, DUST, 0.35);
  },
});
// Решётка жалюзи / радиатора
const grille = (base, axis = 'x', f = 9) => mat(base, {
  fn(o, x, y) { if (((axis === 'x' ? x : y) * f) % 1 < 0.45) mix(o, [15, 15, 12], 0.7); },
});

// Колесо: шина + диск со ступицей и болтами (по координатам в плоскости XZ)
function wheelMat(cx, cz, R, hub, tire = [28, 28, 26]) {
  const h = typeof hub === 'string' ? hex(hub) : hub;
  return mat(tire, {
    fn(o, x, y, z, n) {
      if (Math.abs(n[1]) < 0.5) { if ((Math.atan2(z - cz, x - cx) * 6) % 1 < 0.4) mix(o, [10, 10, 9], 0.5); return; }
      const r = Math.hypot(x - cx, z - cz) / R;
      if (r < 0.66) {
        set(o, h);
        if (r > 0.58) mix(o, [0, 0, 0], 0.35);
        if (r < 0.2) mix(o, [0, 0, 0], 0.4);
        const a = Math.atan2(z - cz, x - cx);
        if (r > 0.33 && r < 0.43 && ((a / (Math.PI * 2)) * 8 + 8) % 1 < 0.3) mix(o, [240, 235, 210], 0.35);
      }
    },
  });
}
// Опорный каток танка: резиновый бандаж и диск
function roadWheel(M, x, cz, R, y0, y1, side) {
  M.cylY(x, cz, R, y0, y1, wheelMat(x, cz, R, PAL[side].c[0], [30, 30, 27]), 14);
}

// Ходовая гусеничной машины (обе стороны). y0..y1 — полоса гусеницы справа (y>0)
function tracks(M, side, o) {
  const { x0, x1, y0, y1, zTop, n, R, sprocketRear = true, returnRollers = 0, skirt = null, idlerR = 0.3 } = o;
  for (const sg of [1, -1]) {
    const ya = sg > 0 ? y0 : -y1, yb = sg > 0 ? y1 : -y0;
    const first = x0 + idlerR + 0.35, last = x1 - idlerR - 0.35;
    const step = (last - first) / (n - 1);
    for (let i = 0; i < n; i++) roadWheel(M, first + i * step, R + 0.05, R, ya + 0.04, yb - 0.04, side);
    // Ленивец и ведущее колесо
    const zi = zTop - idlerR - 0.03;
    M.cylY(x1 - idlerR, zi, idlerR, ya + 0.02, yb - 0.02, wheelMat(x1 - idlerR, zi, idlerR, '#3a3b34'), 12);
    M.cylY(x0 + idlerR, zi, idlerR, ya + 0.02, yb - 0.02, wheelMat(x0 + idlerR, zi, idlerR, '#2e2f2a'), 12);
    for (let i = 0; i < returnRollers; i++) M.cylY(first + ((i + 0.7) * (last - first)) / returnRollers, zTop - 0.2, 0.12, ya + 0.1, yb - 0.1, STEEL, 8);
    // Лента: верхняя и нижняя ветви, наклонные участки
    M.box(x0 + idlerR * 0.6, x1 - idlerR * 0.6, ya, yb, zTop - 0.08, zTop, trackMat);
    M.box(first - 0.1, last + 0.1, ya, yb, 0, 0.09, trackMat);
    M.seg([last + 0.05, (ya + yb) / 2, 0.05], [x1 - idlerR * 0.3, (ya + yb) / 2, zi - idlerR * 0.7], yb - ya, 0.08, trackMat);
    M.seg([first - 0.05, (ya + yb) / 2, 0.05], [x0 + idlerR * 0.3, (ya + yb) / 2, zi - idlerR * 0.7], yb - ya, 0.08, trackMat);
    if (skirt) {
      const [sx0, sx1, sz0, sz1, sm] = skirt;
      const yo = sg > 0 ? [y1, y1 + 0.07] : [-y1 - 0.07, -y1];
      M.box(sx0, sx1, yo[0], yo[1], sz0, sz1, sm);
    }
  }
}

// Колёса грузовика / БТР: оси xs, внешняя кромка yOut
function wheels(M, xs, yOut, R, W, hub = '#3b4430', tread = true) {
  for (const x of xs)
    for (const sg of [1, -1]) {
      const ya = sg > 0 ? yOut - W : -yOut, yb = sg > 0 ? yOut : -yOut + W;
      M.cylY(x, R, R, ya, yb, wheelMat(x, R, R, hub), 16);
    }
}

const rect = (x0, x1, y0, y1) => [[x0, y0], [x1, y0], [x1, y1], [x0, y1]];
// Окно-пластина на грани; n — наружу
function win(M, pts, n, m = GLASS) { M.plate(pts, m, n); }

// Знаки: полоса цвета стороны на боковых гранях в диапазоне x
const stripe = (side, xa, xb, zmin = -1) => (o, x, y, z, n) => {
  if (x > xa && x < xb && Math.abs(n[1]) > 0.6 && z > zmin) set(o, PAL[side].mark);
};
// Знак на крыше (для опознавания с воздуха)
const roofMark = (side, cx, cy, s) => (o, x, y, z, n) => {
  if (n[2] < 0.7) return;
  const dx = Math.abs(x - cx), dy = Math.abs(y - cy);
  if (side === 'red' ? (dx < s * 0.18 && dy < s) || (dy < s * 0.18 && dx < s) : dx < s && dy < s && (dx > s * 0.7 || dy > s * 0.7)) set(o, PAL[side].mark);
};
const both = (...fs) => (o, x, y, z, n) => { for (const f of fs) f(o, x, y, z, n); };

// ---------- Кабины грузовиков ----------
function cabOver(M, side, x0, x1, w, zb, zt, tone) {
  const m = tone || camo(side, 3);
  M.loft([[zb, rect(x0, x1, -w, w)], [zb + 0.9, rect(x0, x1 + 0.02, -w, w)], [zt, rect(x0 + 0.05, x1 - 0.22, -w + 0.06, w - 0.06)]], m);
  const k = (zz) => x1 - ((zz - zb - 0.9) / (zt - zb - 0.9)) * 0.22 + 0.012;
  const za = zb + 1.0, zc = zt - 0.18;
  win(M, [[k(za), -w + 0.15, za], [k(za), w - 0.15, za], [k(zc), w - 0.2, zc], [k(zc), -w + 0.2, zc]], [1, 0, 0.12]);
  for (const sg of [1, -1]) win(M, [[x1 - 0.9, sg * (w + 0.012), za], [x1 - 0.2, sg * (w + 0.012), za], [x1 - 0.25, sg * (w + 0.012 - 0.03), zc], [x1 - 0.9, sg * (w + 0.012 - 0.03), zc]], [0, sg, 0]);
  M.box(x1 - 0.05, x1 + 0.15, -w + 0.05, w - 0.05, zb - 0.15, zb + 0.25, STEEL); // бампер
  M.box(x1 + 0.01, x1 + 0.03, -0.8, 0.8, zb + 0.35, zb + 0.8, grille('#2a2c26', 'y', 8));
  for (const sg of [1, -1]) M.box(x1 + 0.01, x1 + 0.04, sg * (w - 0.35) - 0.12, sg * (w - 0.35) + 0.12, zb + 0.2, zb + 0.34, LIGHT);
  M.box(x0 + 0.3, x0 + 0.9, -0.35, 0.35, zt, zt + 0.06, camo(side, 4)); // люк
  for (const sg of [1, -1]) M.seg([x1 - 0.05, sg * (w + 0.05), zb + 1.2], [x1 + 0.1, sg * (w + 0.3), zb + 1.35], 0.05, 0.05, BLACK); // зеркала
  for (const sg of [1, -1]) M.box(x1 + 0.08, x1 + 0.12, sg * (w + 0.25) - 0.08, sg * (w + 0.25) + 0.08, zb + 1.2, zb + 1.5, GLASS);
}

function cabHood(M, side, x0, x1, hoodEnd, w, zb, zt, tone) {
  const m = tone || camo(side, 3);
  // Капот с крыльями (Урал/Тигр): узкий капот, широкие крылья
  M.loft([[zb, rect(x1, hoodEnd, -0.6, 0.6)], [zb + 0.62, rect(x1, hoodEnd - 0.05, -0.58, 0.58)], [zb + 0.72, rect(x1, hoodEnd - 0.25, -0.5, 0.5)]], m);
  for (const sg of [1, -1]) {
    const ya = sg > 0 ? 0.6 : -w, yb = sg > 0 ? w : -0.6;
    M.loft([[zb + 0.1, rect(x1 + 0.2, hoodEnd - 0.1, ya, yb)], [zb + 0.32, rect(x1 + 0.05, hoodEnd - 0.2, ya, yb)]], m);
    M.box(hoodEnd - 0.25, hoodEnd - 0.12, sg * (w - 0.2) - 0.12, sg * (w - 0.2) + 0.12, zb + 0.32, zb + 0.45, LIGHT);
  }
  M.box(hoodEnd - 0.04, hoodEnd + 0.02, -0.5, 0.5, zb + 0.1, zb + 0.6, grille('#2a2c26', 'y', 9));
  M.box(hoodEnd - 0.05, hoodEnd + 0.2, -w, w, zb - 0.2, zb + 0.08, STEEL);
  // Кабина
  M.loft([[zb, rect(x0, x1, -w, w)], [zt, rect(x0 + 0.05, x1 - 0.15, -w + 0.08, w - 0.08)]], m);
  const za = zb + 0.85, zc = zt - 0.15;
  const k = (zz) => x1 - ((zz - zb) / (zt - zb)) * 0.15 + 0.012;
  win(M, [[k(za), -w + 0.15, za], [k(za), w - 0.15, za], [k(zc), w - 0.2, zc], [k(zc), -w + 0.2, zc]], [1, 0, 0.1]);
  for (const sg of [1, -1]) win(M, [[x0 + 0.2, sg * (w + 0.01), za], [x1 - 0.15, sg * (w + 0.01), za], [x1 - 0.2, sg * (w - 0.06), zc], [x0 + 0.25, sg * (w - 0.06), zc]], [0, sg, 0]);
}

// Кузов с тентом на дугах
function tentBody(M, side, x0, x1, w, zb, tone) {
  const P = PAL[side];
  const cv = mat(side === 'blue' ? '#636847' : '#5b6243', {
    fn(o, x, y, z) {
      if ((((x - x0) / 0.95) % 1) < 0.07) mix(o, [30, 30, 24], 0.35); // дуги
      mix(o, [30, 30, 22], vnoise(x * 1.2, y * 3, z * 3) * 0.25);
    },
  });
  M.box(x0, x1, -w, w, zb, zb + 0.55, tone || camo(side, 5));
  M.loft([[zb + 0.55, rect(x0, x1, -w + 0.02, w - 0.02)], [zb + 1.35, rect(x0, x1, -w + 0.05, w - 0.05)], [zb + 1.72, rect(x0, x1, -w * 0.62, w * 0.62)]], cv);
  void P;
}

// Рама и крылья грузовика
function chassis(M, x0, x1, zb) {
  M.box(x0, x1, -0.5, 0.5, zb - 0.35, zb, flat('#2a2b24'));
}

