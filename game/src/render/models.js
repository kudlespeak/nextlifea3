// Красный крест на белом поле (для санитарных) — сверху и на бортах
function redCross(cx, cy, s) {
  return (o, x, y, z, n) => {
    if (n[2] < 0.7) return;
    const dx = Math.abs(x - cx), dy = Math.abs(y - cy);
    if (dx < s && dy < s) { set(o, [236, 234, 224]); if ((dx < s * 0.22 && dy < s * 0.75) || (dy < s * 0.22 && dx < s * 0.75)) set(o, [200, 36, 32]); }
  };
}
function redCrossSide(cx, cz, s) {
  return (o, x, y, z, n) => {
    if (Math.abs(n[1]) < 0.7 && Math.abs(n[0]) < 0.7) return;
    const u = Math.abs(n[1]) > 0.7 ? x : y;
    const cu = Math.abs(n[1]) > 0.7 ? cx : 0;
    const du = Math.abs(u - cu), dz = Math.abs(z - cz);
    if (du < s && dz < s) { set(o, [236, 234, 224]); if ((du < s * 0.22 && dz < s * 0.75) || (dz < s * 0.22 && du < s * 0.75)) set(o, [200, 36, 32]); }
  };
}

